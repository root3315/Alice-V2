ORDERED = sorted(PAIRS.items(), key=lambda kv: -len(kv[0]))


def main() -> None:
    src = sqlite3.connect(DB)
    src.execute("PRAGMA busy_timeout=8000")
    # консистентный бэкап (работает и при WAL, и при живом писателе)
    dst = sqlite3.connect(BACKUP)
    src.backup(dst)
    dst.close()
    print(f"backup -> {BACKUP}")

    cur = src.cursor()
    tabs = [r[0] for r in cur.execute("select name from sqlite_master where type='table'").fetchall()]
    updated = 0
    leftovers = []
    # Таблицы с FTS-триггерами (нужен токенизатор better_trigram из Node) — их
    # переводит russify_db_fts.cjs; питоновский UPDATE на них падает.
    fts_backed = {"message_log", "diary_entries", "narrative_threads", "album_photos"}
    for t in tabs:
        if "_fts" in t or t in ("sqlite_sequence", "__drizzle_migrations") or t in fts_backed:
            continue
        try:
            cols = [c[1] for c in cur.execute(f"PRAGMA table_info({t})").fetchall()]
        except sqlite3.Error:
            continue
        for col in cols:
            try:
                rows = cur.execute(f"select rowid, {col} from {t} where {col} is not null").fetchall()
            except sqlite3.Error:
                continue
            for rid, val in rows:
                if not isinstance(val, str) or not HAN.search(val):
                    continue
                new = val
                for k, v in ORDERED:
                    new = new.replace(k, v)
                if new != val:
                    cur.execute(f"update {t} set {col} = ? where rowid = ?", (new, rid))
                    updated += 1
                if HAN.search(new):
                    for line in new.split("\n"):
                        if HAN.search(line):
                            leftovers.append(f"{t}.{col}[{rid}]: {line.strip()[:120]}")
    src.commit()
    print(f"updated rows: {updated}")
    if leftovers:
        print(f"ОСТАЛСЯ китайский ({len(leftovers)}):")
        for l in sorted(set(leftovers)):
            print("  !", l)
    else:
        print("китайского в БД не осталось ✓")
    src.close()


if __name__ == "__main__":
    main()
