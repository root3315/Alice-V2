/**
 * Belief Triple — ключевая структура данных Social POMDP.
 *
 * Знания Алисы о мире — не точные значения, а убеждения с неопределённостью.
 * Каждое убеждение представлено тройкой (μ, σ², t_obs):
 *   μ     — оценка среднего ("наиболее вероятное значение")
 *   σ²    — дисперсия ("насколько неопределённо")
 *   t_obs — тик последнего наблюдения ("как давно обновлялось")
 *
 * @see paper-pomdp/ Def 3.1
 */
export interface BeliefTriple {
  /** Оценка среднего. */
  mu: number;
  /** Дисперсия (неопределённость). */
  sigma2: number;
  /** Настенное время последнего наблюдения (мс). Исправление F4: заменено с tick на wall-clock ms, устраняет ускоренное затухание в режиме conversation. */
  tObs: number;
}

export interface BeliefDecayParams {
  /** Период полураспада (секунды). F4: заменено с ticks на seconds, независимо от интервала тика. */
  halfLife: number;
  /** Априорное среднее (цель затухания). */
  muPrior: number;
  /** Верхняя граница стационарной дисперсии. */
  sigma2Inf: number;
  /** Скорость роста дисперсии (в секунду). */
  theta: number;
}

export const DEFAULT_BELIEF_DECAY: BeliefDecayParams = {
  halfLife: 86_400, // 1 день (секунды)
  muPrior: 0, // нейтральный априор
  sigma2Inf: 1.0, // полная неопределённость
  theta: 1 / 60_000, // рост σ²: ~8.3 ч до 63% от σ²_∞
};

/**
 * Параметры затухания для убеждений о чертах характера и интересах.
 * Период полураспада μ короткий (8 ч) — стимулирует LLM постоянно усиливать наблюдения.
 * σ² расширяется очень медленно (θ = 1/6M) — черты личности и интересы являются stable properties:
 * отсутствие наблюдений не означает «стало более неопределённым», а лишь «впечатление ослабло» (μ затухает).
 * Старое θ=1/60000 приводило к σ²→0.95 после 24 ч, условие кристаллизации никогда не выполнялось между сессиями.
 * @see docs/adr/89-impression-formation-system.md §Phase 1
 * @see docs/adr/208-cognitive-label-interest-domain.md
 */
export const TRAIT_BELIEF_DECAY: BeliefDecayParams = {
  halfLife: 28_800, // 8 часов (секунды) — затухание μ для некристаллизованных впечатлений
  muPrior: 0, // нейтральный (нет наблюдений = нет склонности к черте)
  sigma2Inf: 1.0,
  theta: 1 / 6_000_000, // σ² растёт очень медленно: через 24 ч σ²≈0.046 (кристаллизация между сессиями возможна), через 72 ч σ²≈0.10 (нужно накапливать заново)
};

/**
 * Запись журнала изменений убеждения — история наблюдений (paper Def 3.2).
 * Фиксирует состояние до и после каждого вызова BeliefStore.update(), поддерживает причинно-следственную трассировку.
 * @see docs/adr/123-crystallization-substrate-generalization.md §D1
 */
export interface BeliefChangeEntry {
  /** Полный ключ: entityId::domain:attribute */
  key: string;
  /** Среднее до изменения. */
  oldMu: number;
  /** Среднее после изменения. */
  newMu: number;
  /** Дисперсия до изменения. */
  oldSigma2: number;
  /** Дисперсия после изменения. */
  newSigma2: number;
  /** Значение наблюдения. */
  observation: number;
  /** Канал обновления. */
  channel: "structural" | "semantic";
  /** Время изменения (настенное время, мс). */
  ms: number;
}
